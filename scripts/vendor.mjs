import assert from "node:assert/strict";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { build } from "esbuild";

// Paseo compiles plugin source without installing npm dependencies. Commit a
// reproducible, self-contained copy instead of requiring npm on the user's Host.
const source = "node_modules/re2js";
const target = "shared/vendor";
const pkg = JSON.parse(await readFile(`${source}/package.json`, "utf8"));
const result = await build({
  stdin: {
    contents: 'export { RE2JS } from "re2js";',
    resolveDir: process.cwd(),
  },
  bundle: true,
  write: false,
  platform: "browser",
  format: "esm",
  target: "es2020",
  minify: true,
  legalComments: "inline",
  banner: {
    js: `// Generated by scripts/vendor.mjs from re2js ${pkg.version}. See re2js.LICENSE.`,
  },
});
const files = {
  "re2js.js": result.outputFiles[0].text,
  "re2js.d.ts": await readFile(`${source}/build/index.d.ts`, "utf8"),
  "re2js.LICENSE": await readFile(`${source}/LICENSE`, "utf8"),
};
if (process.argv.includes("--write")) await mkdir(target, { recursive: true });
for (const [name, content] of Object.entries(files)) {
  if (process.argv.includes("--write"))
    await writeFile(`${target}/${name}`, content);
  else
    assert.equal(
      await readFile(`${target}/${name}`, "utf8"),
      content,
      `Run npm run vendor:update: ${name}`,
    );
}
console.log(
  `RE2JS ${pkg.version}: bundled source, types and license verified.`,
);
